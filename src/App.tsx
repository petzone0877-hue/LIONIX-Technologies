import React, { useState, useEffect } from 'react';
import { Header } from './components/Header';
import { Sidebar } from './components/Sidebar';
import { PrivatePortalLogin } from './components/PrivatePortalLogin';
import { CompanyOverview } from './components/CompanyOverview';
import { AICompanyManager } from './components/AICompanyManager';
import { AIAgentCenter } from './components/AIAgentCenter';
import { SoftwareBuilder } from './components/SoftwareBuilder';
import { AndroidBuilder } from './components/AndroidBuilder';
import { AgoraManager } from './components/AgoraManager';
import { ServerManager } from './components/ServerManager';
import { DomainDeployment } from './components/DomainDeployment';
import { LivePreviewWorkspace } from './components/LivePreviewWorkspace';
import { StaffManager } from './components/StaffManager';
import { RoleIdCards } from './components/RoleIdCards';
import { QRCodeGenerator } from './components/QRCodeGenerator';
import { SecurityCenter } from './components/SecurityCenter';
import { OwnerControlCenter } from './components/OwnerControlCenter';
import { AIModelManager } from './components/AIModelManager';
import { FileUploadCenter } from './components/FileUploadCenter';
import { AITestingDebugger } from './components/AITestingDebugger';
import { AIStudioWorkspace } from './components/AIStudioWorkspace';
import { ProjectDashboard } from './components/ProjectDashboard';
import { PublicVerificationProfile } from './components/PublicVerificationProfile';

import { CompanyInfo, UserSession, AIDepartment, SoftwareProject, StaffMember } from './types';
import { apiService } from './services/api';

export default function App() {
  const [user, setUser] = useState<UserSession | null>(null);
  const [isCheckingAuth, setIsCheckingAuth] = useState<boolean>(true);
  const [currentTab, setCurrentTab] = useState<string>('ai-studio');
  const [activeLanguage, setActiveLanguage] = useState<'en' | 'bn'>('en');
  const [publicProfileStaffId, setPublicProfileStaffId] = useState<string | null>(null);

  // Core Company Profile State (with uploaded official logo)
  const [company, setCompany] = useState<CompanyInfo>({
    name: 'LIONIX AI Technologies',
    productName: 'LIONIX AI Studio',
    brandName: 'LIONIX',
    tagline: 'BUILD ANYTHING. CREATE EVERYTHING.',
    description: 'An AI-Powered Software Development Company.',
    logoUrl: '/assets/aistudio/WhatsApp_Image_2026-11-01_at_3.45.39_AM-removebg-preview_5500538f.png',
    bannerUrl: 'https://images.unsplash.com/photo-1618005182384-a83a8bd57fbe?auto=format&fit=crop&w=1600&q=80',
    primaryColor: '#F59E0B',
    accentColor: '#D97706',
    ownerEmail: 'liongroupdv@gmail.com',
    foundedYear: '2026',
    headquarters: 'LIONIX AI Tower, Cyber Valley',
    website: 'https://lionix.ai',
    supportEmail: 'liongroupdv@gmail.com',
    phone: '+1 (800) LIONIX-AI',
    mission: 'To empower visionaries and businesses worldwide with autonomous AI software development, removing engineering barriers through natural language intelligence.',
    vision: 'To pioneer the next frontier of sovereign autonomous technology companies, turning human imagination into verified production deliverables.',
    socialLinks: {
      github: 'https://github.com/lionix-ai',
      twitter: 'https://twitter.com/lionix_ai',
      linkedin: 'https://linkedin.com/company/lionix-ai',
    },
    privacyPolicy: 'LIONIX AI Technologies enforces strict zero-trust confidentiality and client data sovereignty.',
    termsAndConditions: 'All autonomous deliverables generated by LIONIX AI Studio are owned solely by the account holder.',
  });

  const [departments, setDepartments] = useState<AIDepartment[]>([]);
  const [currentProject, setCurrentProject] = useState<SoftwareProject | null>(null);
  const [selectedStaffForIdCard, setSelectedStaffForIdCard] = useState<StaffMember | null>(null);

  // 1. Check for public verification profile QR scan URL (?publicProfile=LNX-...)
  useEffect(() => {
    try {
      const params = new URLSearchParams(window.location.search);
      const profileId = params.get('publicProfile');
      if (profileId) {
        setPublicProfileStaffId(profileId);
      }
    } catch (_) {}
  }, []);

  // 2. Initial Auth & Company Profile Check
  useEffect(() => {
    const checkAuthAndCompany = async () => {
      try {
        const comp = await apiService.getCompanyInfo();
        if (comp) setCompany(comp);
      } catch (_) {}

      try {
        if (apiService.hasToken()) {
          const authenticatedUser = await apiService.getCurrentUser();
          if (authenticatedUser) {
            setUser(authenticatedUser);
          } else {
            apiService.removeToken();
            setUser(null);
          }
        } else {
          setUser(null);
        }
      } catch (_) {
        apiService.removeToken();
        setUser(null);
      } finally {
        setIsCheckingAuth(false);
      }
    };

    checkAuthAndCompany();
  }, []);

  // 3. Load private department data once user is authenticated
  useEffect(() => {
    if (user) {
      const fetchPrivateData = async () => {
        try {
          const depts = await apiService.getDepartments();
          if (depts) setDepartments(depts);
        } catch (_) {}
      };
      fetchPrivateData();
    }
  }, [user]);

  const handleLogout = () => {
    apiService.removeToken();
    setUser(null);
    setCurrentTab('overview');
  };

  const handleNavigateToBuilder = (projectId: string) => {
    setCurrentTab('software-builder');
  };

  const handleSelectIdCard = (staff: StaffMember, mode?: 'view' | 'edit') => {
    setSelectedStaffForIdCard(staff);
    if (mode === 'edit') {
      setCurrentTab('edit-idcard');
    } else {
      setCurrentTab('roles-idcards');
    }
  };

  // If a public profile is requested via QR code scan
  if (publicProfileStaffId) {
    return (
      <PublicVerificationProfile
        staffId={publicProfileStaffId}
        company={company}
        onBack={() => {
          window.history.replaceState({}, document.title, window.location.pathname);
          setPublicProfileStaffId(null);
        }}
      />
    );
  }

  // Security Verification Loading Screen
  if (isCheckingAuth) {
    return (
      <div className="min-h-screen bg-[#050608] flex flex-col items-center justify-center p-4">
        <div className="w-20 h-20 rounded-full border-2 border-amber-500/40 p-1 flex items-center justify-center shadow-2xl shadow-amber-500/20 animate-pulse">
          <img
            src={company.logoUrl}
            alt="LIONIX"
            className="w-full h-full object-contain rounded-full"
            onError={(e) => {
              (e.currentTarget as any).src =
                '/assets/aistudio/WhatsApp_Image_2026-11-01_at_3.45.39_AM-removebg-preview_5500538f.png';
            }}
          />
        </div>
        <p className="mt-4 font-cinzel text-xs tracking-widest text-amber-400 font-bold">
          VERIFYING LIONIX PRIVATE PORTAL SESSION...
        </p>
      </div>
    );
  }

  // STRICT RULE: If not authenticated, render ONLY the full-screen Private Portal Login Page!
  // Absolutely no internal company data, dashboard, sidebar, overview, or records are accessible!
  if (!user) {
    return (
      <PrivatePortalLogin
        company={company}
        onLoginSuccess={(authenticatedUser) => {
          setUser(authenticatedUser);
        }}
        language={activeLanguage}
        onToggleLanguage={() => setActiveLanguage((prev) => (prev === 'en' ? 'bn' : 'en'))}
      />
    );
  }

  // Once authenticated and verified via OTP, render the private company portal workspace:
  return (
    <div className="min-h-screen bg-[#07080B] text-zinc-100 flex flex-col font-sans selection:bg-amber-500 selection:text-black">
      {/* Universal Protected Header */}
      <Header
        user={user}
        company={company}
        onSelectTab={(tab) => setCurrentTab(tab)}
        activeLanguage={activeLanguage}
        onToggleLanguage={() => setActiveLanguage((prev) => (prev === 'en' ? 'bn' : 'en'))}
        onLogout={handleLogout}
      />

      <div className="flex-1 flex overflow-hidden">
        {/* Role-Filtered Navigation Sidebar */}
        <Sidebar currentTab={currentTab} onSelectTab={(tab) => setCurrentTab(tab)} user={user} />

        {/* Main Content Workspace */}
        <main className="flex-1 overflow-y-auto p-4 md:p-8">
          <div className="max-w-7xl mx-auto space-y-8 pb-16">
            {currentTab === 'ai-studio' && (
              <AIStudioWorkspace
                user={user}
                currentProject={currentProject}
                onProjectUpdated={(proj) => setCurrentProject(proj)}
                onNavigateTab={(tab) => setCurrentTab(tab)}
                activeLanguage={activeLanguage}
              />
            )}

            {currentTab === 'project-dashboard' && (
              <ProjectDashboard
                user={user}
                onSelectProject={(proj) => {
                  setCurrentProject(proj);
                  setCurrentTab('ai-studio');
                }}
                onNavigateTab={(tab) => setCurrentTab(tab)}
                activeLanguage={activeLanguage}
              />
            )}

            {currentTab === 'overview' && (
              <CompanyOverview
                company={company}
                user={user}
                onCompanyUpdated={(updated) => setCompany(updated)}
                onNavigateTab={(tab) => setCurrentTab(tab)}
              />
            )}

            {currentTab === 'ai-manager' && (
              <AICompanyManager
                departments={departments}
                user={user}
                onProjectCreated={(proj) => setCurrentProject(proj)}
                onNavigateToBuilder={handleNavigateToBuilder}
              />
            )}

            {currentTab === 'ai-agents' && (
              <AIAgentCenter departments={departments} user={user} />
            )}

            {currentTab === 'software-builder' && (
              <SoftwareBuilder
                currentProject={currentProject}
                onProjectUpdated={(proj) => setCurrentProject(proj)}
                user={user}
              />
            )}

            {currentTab === 'android-builder' && (
              <AndroidBuilder currentProject={currentProject} />
            )}

            {currentTab === 'web-builder' && (
              <SoftwareBuilder
                currentProject={currentProject}
                onProjectUpdated={(proj) => setCurrentProject(proj)}
                user={user}
              />
            )}

            {currentTab === 'agora-manager' && <AgoraManager user={user} />}

            {currentTab === 'server-manager' && <ServerManager user={user} />}

            {currentTab === 'domain-deployment' && <DomainDeployment user={user} />}

            {currentTab === 'database-manager' && (
              <SoftwareBuilder
                currentProject={currentProject}
                onProjectUpdated={(proj) => setCurrentProject(proj)}
                user={user}
              />
            )}

            {currentTab === 'live-preview' && (
              <LivePreviewWorkspace currentProject={currentProject} />
            )}

            {currentTab === 'file-upload' && <FileUploadCenter />}

            {currentTab === 'ai-testing' && <AITestingDebugger />}

            {currentTab === 'staff-management' && (
              <StaffManager
                user={user}
                company={company}
                onSelectIdCard={handleSelectIdCard}
              />
            )}

            {currentTab === 'roles-idcards' && (
              <RoleIdCards
                user={user}
                company={company}
                selectedStaff={selectedStaffForIdCard}
                initialMode="view"
                onNavigateTab={(tab) => setCurrentTab(tab)}
              />
            )}

            {currentTab === 'edit-idcard' && (
              <RoleIdCards
                user={user}
                company={company}
                selectedStaff={selectedStaffForIdCard}
                initialMode="edit"
                onNavigateTab={(tab) => setCurrentTab(tab)}
              />
            )}

            {currentTab === 'qr-generator' && (
              <QRCodeGenerator user={user} company={company} />
            )}

            {currentTab === 'ai-models' && <AIModelManager />}

            {currentTab === 'security-center' && <SecurityCenter user={user} />}

            {currentTab === 'owner-center' && (
              <OwnerControlCenter
                user={user}
                company={company}
                departments={departments}
                onNavigateTab={(tab) => setCurrentTab(tab)}
              />
            )}
          </div>
        </main>
      </div>
    </div>
  );
}
